  source VARCHAR(16) NOT NULL COMMENT 'UPLOAD / GENERATED / EDITED',
  status VARCHAR(16) NOT NULL DEFAULT 'UPLOADING' COMMENT 'UPLOADING / READY / FAILED',
  title VARCHAR(256) NOT NULL COMMENT '展示名称',
  description TEXT NULL COMMENT '描述或来源提示词，供搜索',
  source_asset_id BIGINT NULL COMMENT '编辑来源资产，保留溯源',
  width INT NULL COMMENT '主文件宽 px，供筛选',
  height INT NULL COMMENT '主文件高 px，供筛选',
  duration_ms BIGINT NULL COMMENT '主媒体时长 ms',
  trashed_time DATETIME(3) NULL COMMENT '进入回收站时间，必须同时 deleted=1',
  creator VARCHAR(64) NOT NULL DEFAULT '' COMMENT '创建人，遵循芋道 BaseDO',
  create_time DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3) COMMENT '创建时间，统一 UTC',
  updater VARCHAR(64) NOT NULL DEFAULT '' COMMENT '更新人',
  update_time DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3) ON UPDATE CURRENT_TIMESTAMP(3) COMMENT '更新时间，统一 UTC',
  deleted BIT(1) NOT NULL DEFAULT b'0' COMMENT '逻辑删除标记',
  PRIMARY KEY (id),
  UNIQUE KEY uk_asset_scope (tenant_id, workspace_id, id),
  CONSTRAINT fk_asset_ws FOREIGN KEY (tenant_id, workspace_id) REFERENCES aigc_workspace (tenant_id, id),
  CONSTRAINT fk_asset_source FOREIGN KEY (tenant_id, workspace_id, source_asset_id) REFERENCES aigc_asset (tenant_id, workspace_id, id),
  KEY idx_asset_list (tenant_id, workspace_id, deleted, kind, create_time, id),
  KEY idx_asset_filter (tenant_id, workspace_id, deleted, width, height, id),
  CONSTRAINT ck_asset_kind CHECK (kind IN ('IMAGE','VIDEO','MUSIC','AUDIO','DOCUMENT')),
  CONSTRAINT ck_asset_source CHECK (source IN ('UPLOAD','GENERATED','EDITED')),
  CONSTRAINT ck_asset_status CHECK (status IN ('UPLOADING','READY','FAILED')),
  CONSTRAINT ck_asset_size CHECK ((width IS NULL OR width>0) AND (height IS NULL OR height>0) AND (duration_ms IS NULL OR duration_ms>=0)),
  CONSTRAINT ck_asset_trash CHECK (trashed_time IS NULL OR deleted=b'1')
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci COMMENT='资产元信息：上传、生成、编辑结果均可统一管理';

