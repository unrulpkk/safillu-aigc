  KEY idx_asset_file_infra (infra_file_id),
  CONSTRAINT ck_asset_file_size CHECK (byte_size >= 0 AND byte_size <= 536870912),
  CONSTRAINT ck_asset_file_dimensions CHECK ((width IS NULL OR width>0) AND (height IS NULL OR height>0) AND (duration_ms IS NULL OR duration_ms>=0) AND (sample_rate IS NULL OR sample_rate>0) AND (channels IS NULL OR channels>0))
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci COMMENT='资产文件变体：物理存储配置和地址复用 infra_file';

