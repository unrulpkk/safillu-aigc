CREATE TABLE aigc_quota_ledger (
  id BIGINT NOT NULL AUTO_INCREMENT COMMENT '主键，API 序列化为字符串',
  tenant_id BIGINT NOT NULL DEFAULT 0 COMMENT '芋道租户 ID',
  workspace_id BIGINT NOT NULL COMMENT '个人工作空间 ID',
  task_id BIGINT NULL COMMENT '任务，人工发放可为空',
  business_key VARCHAR(128) COLLATE utf8mb4_bin NOT NULL COMMENT 'task:ID:reserve/settle/release 等稳定幂等键',
  entry_type VARCHAR(16) NOT NULL COMMENT 'GRANT / RESERVE / SETTLE / RELEASE / ADJUST',
  available_delta DECIMAL(18,4) NOT NULL COMMENT '可用变化',
  reserved_delta DECIMAL(18,4) NOT NULL COMMENT '冻结变化',
  consumed_delta DECIMAL(18,4) NOT NULL COMMENT '消耗变化',
  available_after DECIMAL(18,4) NOT NULL COMMENT '操作后可用余额',
  reserved_after DECIMAL(18,4) NOT NULL COMMENT '操作后冻结余额',
  consumed_after DECIMAL(18,4) NOT NULL COMMENT '操作后累计消耗',
  remark VARCHAR(500) NULL COMMENT '操作原因',
  creator VARCHAR(64) NOT NULL DEFAULT '' COMMENT '创建人，遵循芋道 BaseDO',
  create_time DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3) COMMENT '创建时间，统一 UTC',
  updater VARCHAR(64) NOT NULL DEFAULT '' COMMENT '更新人',
  update_time DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3) ON UPDATE CURRENT_TIMESTAMP(3) COMMENT '更新时间，统一 UTC',
  deleted BIT(1) NOT NULL DEFAULT b'0' COMMENT '逻辑删除标记',
  PRIMARY KEY (id),
  UNIQUE KEY uk_quota_ledger_scope (tenant_id, workspace_id, id),
  CONSTRAINT fk_quota_ledger_ws FOREIGN KEY (tenant_id, workspace_id) REFERENCES aigc_workspace (tenant_id, id),
  CONSTRAINT fk_ledger_task FOREIGN KEY (tenant_id, workspace_id, task_id) REFERENCES aigc_task (tenant_id, workspace_id, id),
  UNIQUE KEY uk_ledger_business (tenant_id, workspace_id, business_key),
  KEY idx_ledger_list (tenant_id, workspace_id, create_time, id),
  CONSTRAINT ck_ledger_balance CHECK (available_after>=0 AND reserved_after>=0 AND consumed_after>=0),
  CONSTRAINT ck_ledger_delta CHECK ((entry_type='GRANT' AND available_delta>0 AND reserved_delta=0 AND consumed_delta=0) OR (entry_type='RESERVE' AND available_delta<0 AND reserved_delta=-available_delta AND consumed_delta=0) OR (entry_type='SETTLE' AND available_delta=0 AND reserved_delta<0 AND consumed_delta=-reserved_delta) OR (entry_type='RELEASE' AND available_delta>0 AND reserved_delta=-available_delta AND consumed_delta=0) OR (entry_type='ADJUST' AND available_delta<>0 AND reserved_delta=0 AND consumed_delta=0))
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci COMMENT='追加式额度流水：冻结、结算与释放均幂等';

CREATE TABLE aigc_usage_record (
  id BIGINT NOT NULL AUTO_INCREMENT COMMENT '主键，API 序列化为字符串',
  tenant_id BIGINT NOT NULL DEFAULT 0 COMMENT '芋道租户 ID',
  workspace_id BIGINT NOT NULL COMMENT '个人工作空间 ID',
  task_id BIGINT NOT NULL COMMENT '任务 ID',
  attempt_id BIGINT NOT NULL COMMENT '调用尝试 ID',
  provider_usage_key VARCHAR(128) COLLATE utf8mb4_bin NOT NULL COMMENT '规范化用量事件幂等键',
  unit_type VARCHAR(32) NOT NULL COMMENT 'IMAGE / SECOND / CHARACTER / REQUEST / TOKEN 等',
  units DECIMAL(18,4) NOT NULL COMMENT '供应商实际用量',
  cost_minor BIGINT NULL COMMENT '供应商成本最小货币单位，可暂缺',
  currency CHAR(3) NULL COMMENT 'ISO 4217 货币代码',
  usage_summary JSON NOT NULL COMMENT '脱敏用量明细',
  creator VARCHAR(64) NOT NULL DEFAULT '' COMMENT '创建人，遵循芋道 BaseDO',
  create_time DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3) COMMENT '创建时间，统一 UTC',
  updater VARCHAR(64) NOT NULL DEFAULT '' COMMENT '更新人',
  update_time DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3) ON UPDATE CURRENT_TIMESTAMP(3) COMMENT '更新时间，统一 UTC',
  deleted BIT(1) NOT NULL DEFAULT b'0' COMMENT '逻辑删除标记',
  PRIMARY KEY (id),
  UNIQUE KEY uk_usage_record_scope (tenant_id, workspace_id, id),
  CONSTRAINT fk_usage_record_ws FOREIGN KEY (tenant_id, workspace_id) REFERENCES aigc_workspace (tenant_id, id),
  CONSTRAINT fk_usage_task FOREIGN KEY (tenant_id, workspace_id, task_id) REFERENCES aigc_task (tenant_id, workspace_id, id),
  CONSTRAINT fk_usage_attempt FOREIGN KEY (tenant_id, workspace_id, task_id, attempt_id) REFERENCES aigc_task_attempt (tenant_id, workspace_id, task_id, id),
  UNIQUE KEY uk_usage_event (tenant_id, workspace_id, attempt_id, provider_usage_key),
  CONSTRAINT ck_usage_units CHECK (units>=0 AND (cost_minor IS NULL OR cost_minor>=0) AND ((cost_minor IS NULL AND currency IS NULL) OR (cost_minor IS NOT NULL AND currency IS NOT NULL)))
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci COMMENT='供应商用量审计，独立于平台额度和支付';
