CREATE TABLE aigc_workspace (
  id BIGINT NOT NULL AUTO_INCREMENT COMMENT '主键，API 序列化为字符串',
  tenant_id BIGINT NOT NULL DEFAULT 0 COMMENT '芋道租户 ID',
  owner_user_type TINYINT NOT NULL COMMENT '1=member_user；2=system_users',
  owner_user_id BIGINT NOT NULL COMMENT '逻辑引用已有芋道用户 ID',
  name VARCHAR(100) NOT NULL COMMENT '空间名称',
  status VARCHAR(16) NOT NULL DEFAULT 'ENABLED' COMMENT 'ENABLED / DISABLED',
  active_owner_user_id BIGINT GENERATED ALWAYS AS (CASE WHEN deleted = b'0' THEN owner_user_id ELSE NULL END) STORED COMMENT '仅未删除记录参与唯一约束',
  creator VARCHAR(64) NOT NULL DEFAULT '' COMMENT '创建人，遵循芋道 BaseDO',
  create_time DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3) COMMENT '创建时间，统一 UTC',
  updater VARCHAR(64) NOT NULL DEFAULT '' COMMENT '更新人',
  update_time DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3) ON UPDATE CURRENT_TIMESTAMP(3) COMMENT '更新时间，统一 UTC',
  deleted BIT(1) NOT NULL DEFAULT b'0' COMMENT '逻辑删除标记',
  PRIMARY KEY (id),
  UNIQUE KEY uk_workspace_tenant_id (tenant_id, id),
  UNIQUE KEY uk_workspace_owner (tenant_id, owner_user_type, active_owner_user_id),
  CONSTRAINT ck_workspace_owner CHECK (owner_user_type IN (1, 2) AND owner_user_id > 0),
  CONSTRAINT ck_workspace_status CHECK (status IN ('ENABLED', 'DISABLED'))
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci COMMENT='个人创作空间：复用系统身份，不创建业务用户表';

CREATE TABLE aigc_model_capability (
  id BIGINT NOT NULL AUTO_INCREMENT COMMENT '主键，API 序列化为字符串',
  ai_model_id BIGINT NOT NULL COMMENT '逻辑引用 ai_model.id，全局模型注册表',
